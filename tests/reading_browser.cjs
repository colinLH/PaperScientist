const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const base=process.env.READING_BASE_URL || 'http://127.0.0.1:8888';
 const output=process.env.READING_SCREENSHOTS || '.test-output/reading';require('node:fs').mkdirSync(output,{recursive:true});
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/welcome',{waitUntil:'domcontentloaded'});
 await page.locator('#chapters button').last().waitFor();
 assert.equal(await page.locator('#reading-start').isVisible(),false);
 await page.locator('#chapters button').last().click();
 await page.locator('#reading-start').waitFor({state:'visible'});
 await page.screenshot({path:output+'/welcome-desktop.png'});
 await page.locator('#reading-start').click();
 await page.waitForURL('**/reading');
 await page.locator('.report-row').first().waitFor();
 assert.equal(await page.locator('#submit').isEnabled(),true);
 await page.screenshot({path:output+'/desktop.png',fullPage:true});
 await page.locator('.report-row button').first().click();
 await page.locator('#report-dialog[open]').waitFor();
 await page.waitForFunction(()=>[...document.querySelectorAll('#report-body img')].every(i=>i.complete));
 const images=await page.locator('#report-body img').evaluateAll(imgs=>imgs.map(i=>({url:i.src,ok:i.naturalWidth>0})));
 assert.ok(images.length>0);assert.ok(images.every(i=>i.ok),JSON.stringify(images.filter(i=>!i.ok)));
 await page.screenshot({path:output+'/report.png'});
 await page.locator('#close-report').click();
 await page.locator('#filter').fill('No matching report xxx');
 assert.match(await page.locator('#reports').innerText(),/没有匹配/);
 await page.setViewportSize({width:390,height:844});
 await page.locator('#filter').fill('');
 await page.screenshot({path:output+'/mobile.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.goto(base+'/welcome',{waitUntil:'domcontentloaded'});
 await page.locator('#chapters button').last().click();
 await page.locator('#reading-start').waitFor({state:'visible'});
 const bounds=await page.locator('#reading-start').boundingBox();assert.ok(bounds.x>=0&&bounds.x+bounds.width<=390&&bounds.y+bounds.height<800);
 await page.screenshot({path:output+'/welcome-mobile.png'});
 await page.locator('#chapters button').first().click();await page.locator('#reading-start').waitFor({state:'hidden'});assert.equal(await page.locator('#reading-start').isVisible(),false);

 // UI mutation contract uses intercepted responses; no real collection is launched.
 await page.goto(base+'/reading',{waitUntil:'domcontentloaded'});
 const state=await (await page.request.get(base+'/api/reading/status')).json();state.jobs=[];state.ready=true;
 await page.route('**/api/reading/status',route=>route.fulfill({json:state}));
 let submitted=0;
 await page.route('**/api/reading/jobs',async route=>{
  const body=route.request().postDataJSON();assert.equal(body.keywords,'test memory poisoning');assert.equal(body.count,2);submitted++;
  state.jobs=[{sid:'test-ui',keywords:body.keywords,paper_count:body.count,created_at:'2026-10-30',run:{id:'test-run',status:'running',preview:'正在阅读原文'}}];
  await route.fulfill({json:{session_id:'test-ui',run_id:'test-run'}});
 });
 await page.locator('#refresh').click();await page.locator('#keywords').fill('test memory poisoning');
 await page.locator('#submit').click();await page.getByRole('button',{name:'停止',exact:true}).waitFor();
 assert.equal(submitted,1);assert.equal(await page.locator('#submit').isEnabled(),false);
 await page.reload({waitUntil:'domcontentloaded'});await page.getByRole('button',{name:'停止',exact:true}).waitFor();
 await page.route('**/api/reading/jobs/test-run/stop',route=>{state.jobs[0].run.status='stopped';return route.fulfill({json:{status:'stopped'}})});
 await page.getByRole('button',{name:'停止',exact:true}).click();await page.getByRole('button',{name:'继续处理',exact:true}).waitFor();
 await page.route('**/api/reading/jobs/test-run/continue',route=>{state.jobs[0].run.status='waiting_input';state.jobs[0].run.pending={question:'需要补充哪个方向？',question_id:'q1'};return route.fulfill({json:{status:'waiting_input'}})});
 await page.getByRole('button',{name:'继续处理',exact:true}).click();await page.getByLabel('需要补充哪个方向？').fill('保持我的输入');
 await page.waitForTimeout(3500);assert.equal(await page.getByLabel('需要补充哪个方向？').inputValue(),'保持我的输入');
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({desktop:true,mobile:true,welcome_navigation:true,original_images:images.length,preview:true,errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
